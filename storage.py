
"""Persistent DocReaper storage: PostgreSQL in production, SQLite locally."""

from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timedelta, timezone
from typing import Any

from .fingerprints import Fingerprint, jaccard
from .schemas import Book


SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS books (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    title TEXT NOT NULL,
    authors TEXT DEFAULT '',
    year INTEGER,
    edition TEXT DEFAULT '',
    subject TEXT DEFAULT '',
    department TEXT DEFAULT '',
    courses TEXT DEFAULT '',
    level TEXT DEFAULT '',
    description TEXT DEFAULT '',
    source_url TEXT DEFAULT '',
    file_sha256 TEXT UNIQUE,
    text_sha256 TEXT UNIQUE,
    fmt TEXT DEFAULT 'pdf',
    size_bytes INTEGER DEFAULT 0,
    word_count INTEGER DEFAULT 0,
    shingles BLOB,
    storage_path TEXT DEFAULT '',
    license TEXT DEFAULT 'unknown',
    metadata_json TEXT DEFAULT '{}',
    created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_books_word_count ON books(word_count);
CREATE INDEX IF NOT EXISTS idx_books_subject ON books(subject);

CREATE TABLE IF NOT EXISTS discovery (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    url TEXT UNIQUE NOT NULL,
    title TEXT DEFAULT '',
    authors TEXT DEFAULT '',
    source TEXT DEFAULT '',
    subject TEXT DEFAULT '',
    category TEXT DEFAULT '',
    year INTEGER,
    description TEXT DEFAULT '',
    status TEXT DEFAULT 'pending',
    error TEXT DEFAULT '',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TEXT,
    last_attempt_at TEXT,
    created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_discovery_status
ON discovery(status, next_attempt_at);

CREATE TABLE IF NOT EXISTS worker_state (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    status TEXT NOT NULL DEFAULT 'idle',
    pause_requested INTEGER NOT NULL DEFAULT 0,
    stop_requested INTEGER NOT NULL DEFAULT 0,
    heartbeat_at TEXT,
    last_started_at TEXT,
    last_finished_at TEXT,
    last_error TEXT DEFAULT '',
    summary TEXT DEFAULT '{}',
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS run_history (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    status TEXT NOT NULL DEFAULT 'started',
    started_at TEXT NOT NULL,
    finished_at TEXT,
    books_added INTEGER NOT NULL DEFAULT 0,
    candidates_processed INTEGER NOT NULL DEFAULT 0,
    error TEXT DEFAULT '',
    summary TEXT DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS engine_logs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    created_at TEXT NOT NULL,
    level TEXT NOT NULL DEFAULT 'INFO',
    message TEXT NOT NULL,
    run_id INTEGER
);

CREATE INDEX IF NOT EXISTS idx_engine_logs_created
ON engine_logs(created_at DESC);
"""


POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS public.books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    authors TEXT DEFAULT '',
    year INTEGER,
    edition TEXT DEFAULT '',
    subject TEXT DEFAULT '',
    department TEXT DEFAULT '',
    courses TEXT DEFAULT '',
    level TEXT DEFAULT '',
    description TEXT DEFAULT '',
    source_url TEXT DEFAULT '',
    file_sha256 TEXT UNIQUE,
    text_sha256 TEXT UNIQUE,
    fmt TEXT DEFAULT 'pdf',
    size_bytes BIGINT DEFAULT 0,
    word_count INTEGER DEFAULT 0,
    shingles BYTEA,
    storage_path TEXT DEFAULT '',
    license TEXT DEFAULT 'unknown',
    metadata_json JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_books_word_count
ON public.books(word_count);

CREATE INDEX IF NOT EXISTS idx_books_subject
ON public.books(subject);

CREATE TABLE IF NOT EXISTS public.discovery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT UNIQUE NOT NULL,
    title TEXT DEFAULT '',
    authors TEXT DEFAULT '',
    source TEXT DEFAULT '',
    subject TEXT DEFAULT '',
    category TEXT DEFAULT '',
    year INTEGER,
    description TEXT DEFAULT '',
    status TEXT DEFAULT 'pending',
    error TEXT DEFAULT '',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ DEFAULT NOW(),
    last_attempt_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_discovery_status
ON public.discovery(status, next_attempt_at);

CREATE TABLE IF NOT EXISTS public.worker_state (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    status TEXT NOT NULL DEFAULT 'idle',
    pause_requested BOOLEAN NOT NULL DEFAULT FALSE,
    stop_requested BOOLEAN NOT NULL DEFAULT FALSE,
    heartbeat_at TIMESTAMPTZ,
    last_started_at TIMESTAMPTZ,
    last_finished_at TIMESTAMPTZ,
    last_error TEXT DEFAULT '',
    summary JSONB DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.worker_state (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.run_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status TEXT NOT NULL DEFAULT 'started',
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    books_added INTEGER NOT NULL DEFAULT 0,
    candidates_processed INTEGER NOT NULL DEFAULT 0,
    error TEXT DEFAULT '',
    summary JSONB DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS public.engine_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    level TEXT NOT NULL DEFAULT 'INFO',
    message TEXT NOT NULL,
    run_id BIGINT REFERENCES public.run_history(id)
);

CREATE INDEX IF NOT EXISTS idx_engine_logs_created
ON public.engine_logs(created_at DESC);
"""


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _iso_now() -> str:
    return _now().isoformat()


class Store:
    """Database adapter with a common interface for both database engines."""

    def __init__(
        self,
        database_url: str = "sqlite:///./docreaper.db",
    ):
        self.is_postgres = database_url.startswith(
            ("postgresql://", "postgres://")
        )

        if self.is_postgres:
            try:
                import psycopg
                from psycopg.rows import dict_row
            except ImportError as exc:
                raise RuntimeError(
                    "PostgreSQL support requires psycopg. "
                    "Install psycopg[binary]>=3.2."
                ) from exc

            self.conn = psycopg.connect(
                database_url,
                row_factory=dict_row,
                connect_timeout=20,
            )

            try:
                for statement in POSTGRES_SCHEMA.split(";"):
                    statement = statement.strip()

                    if statement:
                        self.conn.execute(statement)

                self.conn.commit()

            except Exception:
                self.conn.rollback()
                self.conn.close()
                raise

        else:
            self.conn = sqlite3.connect(
                self._sqlite_path(database_url),
                timeout=30,
            )
            self.conn.row_factory = sqlite3.Row
            self.conn.executescript(SQLITE_SCHEMA)
            self.conn.commit()

        self._ensure_worker_state()

    @staticmethod
    def _sqlite_path(database_url: str) -> str:
        for prefix in ("sqlite:///", "sqlite://"):
            if database_url.startswith(prefix):
                return database_url[len(prefix):] or ":memory:"
        return database_url or ":memory:"

    def close(self) -> None:
        self.conn.close()

    def _execute(self, sql: str, params: tuple = ()):
        if self.is_postgres:
            sql = sql.replace("?", "%s")
        return self.conn.execute(sql, params)

    def _commit(self) -> None:
        self.conn.commit()

    def _ensure_worker_state(self) -> None:
        if self.is_postgres:
            self._execute(
                """
                INSERT INTO worker_state (id)
                VALUES (1)
                ON CONFLICT (id) DO NOTHING
                """
            )
        else:
            self._execute(
                """
                INSERT OR IGNORE INTO worker_state
                (id, updated_at)
                VALUES (1, ?)
                """,
                (_iso_now(),),
            )
        self._commit()

    @staticmethod
    def _dict(row) -> dict | None:
        if row is None:
            return None
        return dict(row)

    # ---------------------------------------------------------
    # DISCOVERY QUEUE
    # ---------------------------------------------------------

    def add_discovery(self, rec) -> bool:
        """Insert a candidate without duplicating an existing URL."""

        values = (
            rec.url,
            rec.title,
            rec.authors,
            rec.source,
            rec.subject,
            rec.category,
            rec.year,
            rec.description,
        )

        if self.is_postgres:
            cur = self._execute(
                """
                INSERT INTO discovery
                (url, title, authors, source, subject, category,
                 year, description)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT (url) DO NOTHING
                RETURNING id
                """,
                values,
            )
            inserted = cur.fetchone() is not None
        else:
            cur = self._execute(
                """
                INSERT OR IGNORE INTO discovery
                (url, title, authors, source, subject, category,
                 year, description, created_at, next_attempt_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (*values, _iso_now(), _iso_now()),
            )
            inserted = cur.rowcount > 0

        self._commit()
        return inserted

    def pending_discoveries(self, limit: int = 50) -> list[dict]:
        """Return pending candidates and failed candidates due for retry."""

        if self.is_postgres:
            rows = self._execute(
                """
                SELECT *
                FROM discovery
                WHERE status = 'pending'
                   OR (
                       status = 'failed'
                       AND attempts < 8
                       AND next_attempt_at <= NOW()
                   )
                ORDER BY
                    CASE WHEN status = 'pending' THEN 0 ELSE 1 END,
                    id
                LIMIT ?
                """,
                (limit,),
            ).fetchall()
        else:
            rows = self._execute(
                """
                SELECT *
                FROM discovery
                WHERE status = 'pending'
                   OR (
                       status = 'failed'
                       AND attempts < 8
                       AND next_attempt_at <= ?
                   )
                ORDER BY
                    CASE WHEN status = 'pending' THEN 0 ELSE 1 END,
                    id
                LIMIT ?
                """,
                (_iso_now(), limit),
            ).fetchall()

        return [dict(row) for row in rows]

    def mark_discovery_attempt(self, url: str) -> None:
        """Record that processing of a candidate has begun."""

        self._execute(
            """
            UPDATE discovery
            SET attempts = attempts + 1,
                last_attempt_at = CURRENT_TIMESTAMP
            WHERE url = ?
            """,
            (url,),
        )
        self._commit()

    def set_discovery_status(
        self,
        url: str,
        status: str,
        error: str = "",
    ) -> None:
        """Update candidate state and schedule a bounded retry if needed."""

        if status == "failed":
            if self.is_postgres:
                self._execute(
                    """
                    UPDATE discovery
                    SET status = 'failed',
                        error = ?,
                        next_attempt_at =
                            NOW() + LEAST(
                                POWER(2, LEAST(attempts, 7)) * INTERVAL '1 minute',
                                INTERVAL '24 hours'
                            )
                    WHERE url = ?
                    """,
                    (error[:1000], url),
                )
            else:
                row = self._execute(
                    "SELECT attempts FROM discovery WHERE url = ?",
                    (url,),
                ).fetchone()
                attempts = row["attempts"] if row else 0
                delay_minutes = min(2 ** min(attempts, 7), 1440)
                next_attempt = (
                    _now() + timedelta(minutes=delay_minutes)
                ).isoformat()
                self._execute(
                    """
                    UPDATE discovery
                    SET status = 'failed',
                        error = ?,
                        next_attempt_at = ?
                    WHERE url = ?
                    """,
                    (error[:1000], next_attempt, url),
                )
        else:
            self._execute(
                """
                UPDATE discovery
                SET status = ?, error = ?
                WHERE url = ?
                """,
                (status, error[:1000], url),
            )

        self._commit()

    # ---------------------------------------------------------
    # BOOK CATALOGUE
    # ---------------------------------------------------------

    def count_books(self) -> int:
        row = self._execute(
            "SELECT COUNT(*) AS total FROM books"
        ).fetchone()
        return row["total"]

    def has_file_sha256(self, file_sha256: str) -> bool:
        row = self._execute(
            "SELECT 1 FROM books WHERE file_sha256 = ?",
            (file_sha256,),
        ).fetchone()
        return row is not None

    def has_text_sha256(self, text_sha256: str) -> bool:
        row = self._execute(
            "SELECT 1 FROM books WHERE text_sha256 = ?",
            (text_sha256,),
        ).fetchone()
        return row is not None

    def add_book(
        self,
        book: Book,
        fp: Fingerprint,
        storage_path: str,
    ) -> int:
        values = (
            book.title,
            book.authors,
            book.year,
            book.edition,
            book.subject,
            book.department,
            book.courses,
            book.level,
            book.description,
            book.source_url,
            fp.file_sha256,
            fp.text_sha256,
            book.fmt,
            book.size_bytes,
            fp.word_count,
            fp.pack_shingles(),
            storage_path,
            book.license,
        )

        if self.is_postgres:
            from psycopg.types.json import Jsonb

            cur = self._execute(
                """
                INSERT INTO books
                (title, authors, year, edition, subject, department,
                 courses, level, description, source_url, file_sha256,
                 text_sha256, fmt, size_bytes, word_count, shingles,
                 storage_path, license, metadata_json)
                VALUES
                (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                RETURNING id
                """,
                (*values, Jsonb(book.metadata)),
            )
            book_id = cur.fetchone()["id"]
        else:
            cur = self._execute(
                """
                INSERT INTO books
                (title, authors, year, edition, subject, department,
                 courses, level, description, source_url, file_sha256,
                 text_sha256, fmt, size_bytes, word_count, shingles,
                 storage_path, license, metadata_json, created_at)
                VALUES
                (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (*values, json.dumps(book.metadata), _iso_now()),
            )
            book_id = cur.lastrowid

        self._commit()
        return book_id

    def near_duplicate(
        self,
        shingles: frozenset[int],
        word_count: int,
        threshold: float,
    ) -> dict | None:
        """Compare shingle sets against books in a similar word-count range."""

        lo = word_count // 2
        hi = max(word_count * 2, 1)

        rows = self._execute(
            """
            SELECT id, title, shingles
            FROM books
            WHERE word_count BETWEEN ? AND ?
              AND shingles IS NOT NULL
            """,
            (lo, hi),
        )

        for row in rows:
            score = jaccard(
                shingles,
                Fingerprint.unpack_shingles(bytes(row["shingles"])),
            )

            if score is not None and score >= threshold:
                return {
                    "id": row["id"],
                    "title": row["title"],
                    "score": score,
                }

        return None

    def recent_books(self, limit: int = 10) -> list[dict]:
        rows = self._execute(
            """
            SELECT id, title, authors, year, subject, fmt,
                   size_bytes, word_count, license, storage_path,
                   created_at
            FROM books
            ORDER BY id DESC
            LIMIT ?
            """,
            (limit,),
        ).fetchall()

        return [dict(row) for row in rows]

    def stats(self) -> dict:
        books = self._execute(
            """
            SELECT subject, COUNT(*) AS n
            FROM books
            GROUP BY subject
            ORDER BY n DESC
            """
        ).fetchall()

        counts = self._execute(
            """
            SELECT status, COUNT(*) AS n
            FROM discovery
            GROUP BY status
            """
        ).fetchall()

        by_status = {row["status"]: row["n"] for row in counts}

        return {
            "books": self.count_books(),
            "by_subject": {
                row["subject"]: row["n"] for row in books
            },
            "discovery_pending": by_status.get("pending", 0),
            "discovery_kept": by_status.get("kept", 0),
            "discovery_duplicate": by_status.get("duplicate", 0),
            "discovery_failed": by_status.get("failed", 0),
            "discovery_skipped": by_status.get("skipped", 0),
        }

    # ---------------------------------------------------------
    # WORKER STATE
    # ---------------------------------------------------------

    def get_worker_state(self) -> dict:
        row = self._execute(
            "SELECT * FROM worker_state WHERE id = 1"
        ).fetchone()

        result = self._dict(row) or {}

        if isinstance(result.get("summary"), str):
            try:
                result["summary"] = json.loads(result["summary"])
            except (TypeError, ValueError):
                result["summary"] = {}

        return result

    def update_worker_state(self, **fields: Any) -> None:
        allowed = {
            "status",
            "pause_requested",
            "stop_requested",
            "heartbeat_at",
            "last_started_at",
            "last_finished_at",
            "last_error",
            "summary",
        }

        updates = {
            key: value
            for key, value in fields.items()
            if key in allowed
        }

        if not updates:
            return

        if "summary" in updates:
            if self.is_postgres:
                from psycopg.types.json import Jsonb
                updates["summary"] = Jsonb(updates["summary"])
            else:
                updates["summary"] = json.dumps(updates["summary"])

        if not self.is_postgres:
            for key in ("pause_requested", "stop_requested"):
                if key in updates:
                    updates[key] = int(bool(updates[key]))

        assignments = ", ".join(
            f"{key} = ?" for key in updates
        )
        values = tuple(updates.values()) + (_iso_now(),)

        self._execute(
            f"""
            UPDATE worker_state
            SET {assignments}, updated_at = ?
            WHERE id = 1
            """,
            values,
        )
        self._commit()

    # ---------------------------------------------------------
    # RUN HISTORY
    # ---------------------------------------------------------

    def start_run(self) -> int:
        if self.is_postgres:
            cur = self._execute(
                """
                INSERT INTO run_history (status)
                VALUES ('running')
                RETURNING id
                """
            )
            run_id = cur.fetchone()["id"]
        else:
            cur = self._execute(
                """
                INSERT INTO run_history (status, started_at)
                VALUES ('running', ?)
                """,
                (_iso_now(),),
            )
            run_id = cur.lastrowid

        self._commit()
        return run_id

    def finish_run(
        self,
        run_id: int,
        *,
        status: str,
        books_added: int = 0,
        candidates_processed: int = 0,
        error: str = "",
        summary: dict | None = None,
    ) -> None:
        summary = summary or {}

        if self.is_postgres:
            from psycopg.types.json import Jsonb
            summary_value = Jsonb(summary)
        else:
            summary_value = json.dumps(summary)

        self._execute(
            """
            UPDATE run_history
            SET status = ?,
                finished_at = CURRENT_TIMESTAMP,
                books_added = ?,
                candidates_processed = ?,
                error = ?,
                summary = ?
            WHERE id = ?
            """,
            (
                status,
                books_added,
                candidates_processed,
                error[:2000],
                summary_value,
                run_id,
            ),
        )
        self._commit()

    # ---------------------------------------------------------
    # PERSISTENT ENGINE LOGS
    # ---------------------------------------------------------

    def add_log(
        self,
        message: str,
        level: str = "INFO",
        run_id: int | None = None,
    ) -> int:
        if self.is_postgres:
            cur = self._execute(
                """
                INSERT INTO engine_logs (level, message, run_id)
                VALUES (?, ?, ?)
                RETURNING id
                """,
                (level, message, run_id),
            )
            log_id = cur.fetchone()["id"]
        else:
            cur = self._execute(
                """
                INSERT INTO engine_logs
                (created_at, level, message, run_id)
                VALUES (?, ?, ?, ?)
                """,
                (_iso_now(), level, message, run_id),
            )
            log_id = cur.lastrowid

        self._commit()
        return log_id

    def recent_logs(
        self,
        after: int = 0,
        limit: int = 250,
    ) -> list[dict]:
        rows = self._execute(
            """
            SELECT id, created_at, level, message, run_id
            FROM engine_logs
            WHERE id > ?
            ORDER BY id ASC
            LIMIT ?
            """,
            (after, limit),
        ).fetchall()

        return [dict(row) for row in rows]
